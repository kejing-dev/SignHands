package io.embodit.signhands.domain

import org.json.JSONObject

/** Finger ids in the order the matcher, the tints and the hand model's material slots use. */
enum class Finger { THUMB, INDEX, MIDDLE, RING, PINKY }

/**
 * Joint order of the app's 25-joint hand (no PALM; the WebXR model's joints, PICO HandJoint names):
 * WRIST, THUMB metacarpal / proximal / distal / tip, then INDEX, MIDDLE, RING, LITTLE x metacarpal /
 * proximal / intermediate / distal / tip.
 */
object J {
    const val WRIST = 0
    const val THUMB_MC = 1
    const val THUMB_TIP = 4
    const val COUNT = 25

    /** First joint (metacarpal) of finger 0..3 (index..pinky). */
    fun base(finger: Int): Int = 5 + finger * 5

    fun prox(finger: Int): Int = base(finger) + 1

    fun tip(finger: Int): Int = base(finger) + 4
}

/** One letter of asl_letters.json (generated by tools/bake_hands.py from the design package). */
data class Letter(
    val l: String,
    val clipStart: Float,
    /** Orientation of the hand in the practice frame (right hand). */
    val orient: Q4,
    val orientName: String,
    val thumb: String,
    val thumbFirst: Boolean,
    val motion: String?,
    val scored: Boolean,
    val tipZh: String,
    val tipEn: String,
    /** "ok" and one variant per deliberately wrong finger ("thumb", "index", ...): 25 joints, hand frame, right hand. */
    val joints: Map<String, List<V3>>,
) {
    val isMotion: Boolean
        get() = motion != null

    fun tip(lang: Lang): String = if (lang == Lang.EN) tipEn else tipZh
}

data class LessonDef(val n: Int, val letters: List<String>, val words: List<String>)

class LetterBook(val letters: Map<String, Letter>, val lessons: List<LessonDef>, val clipSegment: Float, val morphSec: Float, val modelHandLength: Float) {
    operator fun get(l: String): Letter = letters[l] ?: error("no letter $l")

    val alphabet: List<String> = ('A'..'Z').map { it.toString() }

    fun lesson(n: Int): LessonDef = lessons.first { it.n == n }

    companion object {
        fun parse(json: String): LetterBook {
            val root = JSONObject(json)
            val letters = LinkedHashMap<String, Letter>()
            val arr = root.getJSONArray("letters")
            for (i in 0 until arr.length()) {
                val o = arr.getJSONObject(i)
                val orient = o.getJSONArray("orient")
                val jointsObj = o.getJSONObject("joints")
                val joints = HashMap<String, List<V3>>()
                for (key in jointsObj.keys()) {
                    val pts = jointsObj.getJSONArray(key)
                    joints[key] = List(pts.length()) { k -> pts.getJSONArray(k).let { p -> V3(p.getDouble(0).toFloat(), p.getDouble(1).toFloat(), p.getDouble(2).toFloat()) } }
                }
                val l = o.getString("l")
                letters[l] =
                    Letter(
                        l = l,
                        clipStart = o.getDouble("clipStart").toFloat(),
                        orient = Q4.eulerXyz(orient.getDouble(0).toFloat(), orient.getDouble(1).toFloat(), orient.getDouble(2).toFloat()),
                        orientName = o.getString("orientName"),
                        thumb = o.getString("thumb"),
                        thumbFirst = o.optBoolean("thumbFirst"),
                        motion = if (o.isNull("motion")) null else o.optString("motion").ifEmpty { null },
                        // v0.1.3 (profile D27): every letter is judged now (J / Z by their path, M / N / T by the fist + tucked thumb)
                        scored = l != "OPEN",
                        tipZh = o.optString("tipZh"),
                        tipEn = o.optString("tipEn"),
                        joints = joints,
                    )
            }
            val lessons = ArrayList<LessonDef>()
            val la = root.getJSONArray("lessons")
            for (i in 0 until la.length()) {
                val o = la.getJSONObject(i)
                val ls = o.optJSONArray("letters")
                val ws = o.optJSONArray("words")
                lessons +=
                    LessonDef(
                        n = o.getInt("n"),
                        letters = if (ls == null) emptyList() else List(ls.length()) { ls.getString(it) },
                        words = if (ws == null) emptyList() else List(ws.length()) { ws.getString(it) },
                    )
            }
            return LetterBook(letters, lessons, root.getDouble("clipSegment").toFloat(), root.getDouble("morphSec").toFloat(), root.getDouble("modelHandLength").toFloat())
        }
    }
}

enum class Lang { SYSTEM, ZH, EN }

enum class Handed { RIGHT, LEFT }

enum class GhostMode { OVERLAY, SIDE }
